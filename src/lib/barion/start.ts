/**
 * Payment/Start v2 — új azonnali (Immediate) fizetés indítása a Barionban.
 *
 * Fix üzleti szabályok (a lib állítja, a hívó nem felülírható módon kapja):
 * - PaymentType: Immediate (előleg/részletfizetés nincs)
 * - GuestCheckOut: true (Barion-fiók nélkül is fizethet a vevő). A
 *   barion-web-php v3.0.0 (2026-06-17) kivette a mezőt a saját modelljéből, a
 *   Payment-Start-v2 doksi (2026-01-07) viszont továbbra is „Required"-ként
 *   írja le; amíg a doksi nem ejti, küldjük.
 * - FundingSources: ['All']
 * - Locale: 'hu-HU', Currency: 'HUF'
 * - PaymentWindow: default '00:30:00' (paraméterezhető)
 * - PaymentRequestId: a rendelés orderNumber-e (pl. KH-2026-000123). A Barion
 *   doksija szerint ez CSAK azonosító a bolt saját nyilvántartásához és a havi
 *   kivonathoz („The unique identifier for the payment generated by the shop.
 *   This is so the shop can track its own payment identifiers."); a Barion
 *   NEM dokumentál hozzá deduplikációt, tehát egy ismételt Start ugyanazzal a
 *   PaymentRequestId-vel ÚJ fizetést hozhat létre. A Start ezért sosem fut
 *   újra automatikusan (start-checkout.ts: bizonytalan kimenetnél a rendelés
 *   payment_pending marad a fizetési ablak végéig). Az Idempotency-Key fejléc
 *   (csak a PHP SDK-ban dokumentált) tudatosan HALASZTVA: az újrajátszás
 *   élettartama és a 409/422 viselkedése nincs leírva.
 * - OrderNumber: szintén az orderNumber (opcionális mező, a havi kivonaton és
 *   a tranzakció-exportban is megjelenik, Payment-Start-v2).
 *
 * Összegszámítás NINCS a libben: a tranzakciók Total/ItemTotal értékeit a
 * hívó adja, szerver-oldalon validálva (az orders snapshot-árai a forrás).
 *
 * 3DS-adatok (BillingAddress, PurchaseInformation, PayerAccountInformation,
 * ChallengePreference): a Payment-Start-v2 szerint „if the merchant does not
 * provide 3DS-related properties, it doesn't mean that the payment will fail.
 * It means that the payer will have a higher chance of getting a challenge
 * during payment." Digitális kurzusnál a vevőnek nem kell kihívást kapnia
 * csak azért, mert semmit nem küldtünk. Egy ROSSZ érték viszont minden
 * Startot elutasíttatna (ModelValidationError), vagyis minden eladás megállna.
 * Ezért minden mezőnév, enum-érték és hosszkorlát két forrásból ellenőrzött:
 * a docs.barion.com oldalai (Wayback: Payment-Start-v2 20260122015633,
 * BillingAddress 20241110122232, PurchaseInformation 20260122003811,
 * PayerAccountInformation 20241110113244, DeliveryTimeframeType
 * 20241014080354, ShippingAddressIndicator 20241014091045, PurchaseType
 * 20241014092043, ChallengePreference 20260122020254) és a hivatalos
 * barion-web-php modelljei és enumerációi (Models/Payment/
 * PreparePaymentRequestModel, Models/ThreeDSecure/*, Enumerations/ThreeDSecure/*).
 * Amit nem tudunk bizonyítottan helyes értékkel kitölteni, az kimarad (pl.
 * Region, ReOrderIndicator, telefonszám). A BARION_SEND_3DS='false'
 * vészkapcsoló a négy 3DS-blokkot hagyja ki (az OrderNumbert nem), lásd
 * `barionSend3dsEnabled`. Az élesítés a tulajdonossal egyeztetett idősávban
 * történik, élő próbával (sandbox-kártyánál a 3DS nem fut): két, legalább
 * 10 Ft-os (`BARION_MIN_TRANSACTION_HUF`) termékre indított, a Barion-oldalon
 * fizetés nélkül otthagyott Payment/Start, egy vendégként és egy
 * bejelentkezett vevőként, mert a PayerAccountInformation a kettőben más
 * (NoAccount, illetve AccountId + AccountCreated + a fiók korának sávja). Ez
 * 0 Ft-ba kerül, és mindkét vevőtípus body-ját élőben ellenőrzi, mert a
 * ModelValidationError magából a Startból jön vissza; a fiók korának többi
 * sávját (amelybe a próbafiók nem esik) csak a fenti két forrás igazolja. A
 * próbavevővel (e-mail-cím, illetve fiók) az előző 30 percben
 * (BARION_DEFAULT_PAYMENT_WINDOW) nem indulhatott fizetés ugyanarra a
 * kurzusra: egyező adatoknál a pénztár a még nyitott fizetést folytatja
 * (start-checkout.ts, resolveDuplicatePurchase: 'resume'), új Start nem megy
 * ki, a Barion-oldal mégis megnyílik, és a próba sikeresnek látszana. Ezért a
 * runbook azt is ellenőrizteti, hogy mindkét próbához új rendelés jött létre.
 * A kihívás-ág (challenge) ellenőrzéséhez ezt követheti egy valódi, legalább
 * 10 Ft-os kártyás vásárlás és annak visszatérítése a Kineticare adminjából.
 *
 * Recurring-előkészítés (jövőbeli tokenfizetés): az InitiateRecurrence és a
 * RecurrenceId csak akkor kerül a kérésbe, ha a BARION_RECURRING_ENABLED
 * feature-flag 'true' ÉS a hívó kéri. Flag nélkül a recurring-paraméter
 * megadása hibát dob — így nem maradhat észrevétlen, hogy a recurring
 * ténylegesen ki van kapcsolva.
 */

export const BARION_DEFAULT_PAYMENT_WINDOW = '00:30:00'

