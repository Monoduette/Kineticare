/** Folyamatonként egyszer: a Start minden hívása olvassa a kapcsolót. */
let unrecognisedSend3dsWarned = false

function warnUnrecognisedSend3dsOnce(): void {
  if (unrecognisedSend3dsWarned) {
    return
  }
  unrecognisedSend3dsWarned = true
  // Az értéket nem naplózzuk: egy rossz helyre másolt titok is lehet.
  createLogger({ module: 'barion' }).warn(
    'A BARION_SEND_3DS értéke nem ismert, ezért a 3DS-adatok küldése bekapcsolva marad. Kikapcsolni kizárólag a „false” érték tudja.',
    { envKey: 'BARION_SEND_3DS', effective3ds: true },
  )
}

/**
 * A 3DS-blokkok vészkapcsolója (BARION_SEND_3DS). Alapból BE; kizárólag a szó
 * szerinti 'false' kapcsolja ki (kis-nagybetű és szóköz mindegy). A többi
 * Barion-kulcsot a client.ts `getBarionConfig` olvassa, és az src/env.ts
 * ellenőrzi; ez a kapcsoló helyben olvas (a két fájl más csomag tulajdona), és
 * minden Startnál újra, tehát egy élesben elutasított 3DS-kérés (a RIASZTÁS
 * ModelValidationError-t mutat) egyetlen változó átírásával visszaállítható
 * a korábbi, 3DS nélküli kérésre.
 *
 * A szigorú értelmezés szándékos (a BARION_RECURRING_ENABLED is pontos
 * egyezést vár): a '0', 'off', 'no', 'ki', 'nem' NEM kapcsol ki. Hogy egy
 * ilyen, félreértett érték ne maradjon néma, a nem üres, se 'true', se
 * 'false' értékre a folyamat egyszer figyelmeztet a naplóban (a 3DS ilyenkor
 * bekapcsolva marad). Az üzemeltetői útmutató:
 * docs/uzemeltetes/11-riasztas-es-ugyelet.md („A 3DS-vészkapcsoló”).
 */
export function barionSend3dsEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  const raw = env.BARION_SEND_3DS
  const normalized = typeof raw === 'string' ? raw.trim().toLowerCase() : ''
  if (normalized !== '' && normalized !== 'true' && normalized !== 'false') {
    warnUnrecognisedSend3dsOnce()
  }
  return normalized !== 'false'
}

/** Egysoros, összevont szóközű szöveg, legfeljebb `max` karakter (Unicode-karakterben mérve). */
function fitText(value: string, max: number): string {
  const normalized = value.replace(/\s+/g, ' ').trim()
  const chars = Array.from(normalized)
  return chars.length <= max ? normalized : chars.slice(0, max).join('').trimEnd()
}

/** A kártyabirtokos-név javaslata a Barion 2–45 karakteres korlátján belül; rövidebbre nincs javaslat. */
export function cardHolderNameHintFor(name: string | undefined): string | undefined {
  if (name === undefined) {
    return undefined
  }
  const hint = fitText(name, BARION_CARD_HOLDER_NAME_MAX)
  return Array.from(hint).length < BARION_CARD_HOLDER_NAME_MIN ? undefined : hint
}

/**
 * Legfeljebb `max` UTF-16 kódegység, kódpont közepén nem vágva. A Barion .NET
 * alapú, a „Maximum N characters" ott a string hossza (UTF-16); a magyar
 * ékezetes betűk egy egységnyiek, de egy emoji kettő, ezért itt nem a
 * kódpontot számoljuk.
 */
function fitUtf16(value: string, max: number): string {
  const normalized = value.replace(/\s+/g, ' ').trim()
  if (normalized.length <= max) {
    return normalized
  }
  let out = ''
  for (const char of normalized) {
    if (out.length + char.length > max) {
      break
    }
    out += char
  }
  return out.trimEnd()
}

/**
 * A Barion 3DS-dátumalakja: UTC, ezredmásodperccel, `Z` NÉLKÜL. A doksi
 * (PurchaseInformation, PayerAccountInformation) szövege: „In UTC Expected
 * format: "2019-06-27T07:15:51.327"". Az ISO-alak `Z` utótagja ezért kerül le.
 */
export function barionUtcTimestamp(date: Date): string {
  return date.toISOString().replace(/Z$/, '')
}

const DAY_MS = 24 * 60 * 60 * 1000

/**
 * A fiók kora → AccountCreationIndicator. Az értékkészlet a barion-web-php
 * Enumerations/ThreeDSecure/AccountCreationIndicator enumja (NoAccount,
 * CreatedDuringThisTransaction, LessThan30Days, Between30And60Days,
 * MoreThan60Days); a határok az enum-nevekből. Jövőbeli (órahibás)
 * létrehozási időnél a „friss" sáv megy ki, nem dobunk.
 */
export function accountCreationIndicatorFor(
  accountCreated: Date,
  now: Date,
): BarionAccountCreationIndicator {
  const ageDays = (now.getTime() - accountCreated.getTime()) / DAY_MS
  if (ageDays < 30) {
    return 'LessThan30Days'
  }
  if (ageDays <= 60) {
    return 'Between30And60Days'
  }
  return 'MoreThan60Days'
}

/**
 * Az utca + házszám legfeljebb három, egyenként 50 egységes sorra bontva
 * (Street, Street2, Street3). Szóhatáron vágunk, ha a sorban van szóköz;
 * különben keményen. A harmadik sor utáni maradék elvész: a 3DS-cím
 * kockázatelemzésre szolgál, a számla a teljes címet a rendelés snapshotjából
 * kapja.
 */
export function splitStreetLines(street: string): string[] {
  const lines: string[] = []
  let rest = Array.from(street.replace(/\s+/g, ' ').trim())
  while (rest.length > 0 && lines.length < BARION_BILLING_STREET_LINES) {
    const whole = rest.join('')
    if (whole.length <= BARION_BILLING_STREET_MAX) {
      lines.push(whole)
      break
    }
    // Hány kódpont fér a sorba UTF-16-ban mérve.
    let fit = 0
    let units = 0
    while (fit < rest.length && units + rest[fit].length <= BARION_BILLING_STREET_MAX) {
      units += rest[fit].length
      fit += 1
    }
    // Szóhatár: ha a következő kódpont szóköz, a teljes sor jó; különben az
    // utolsó szóközig vágunk (ha van a sorban).
    let cut = fit
    if (rest[fit] !== ' ') {
      const lastSpace = rest.slice(0, fit).lastIndexOf(' ')
      if (lastSpace > 0) {
        cut = lastSpace
      }
    }
    lines.push(rest.slice(0, cut).join('').trimEnd())
    rest = Array.from(rest.slice(cut).join('').trim())
  }
  return lines
}

function mapBillingAddress(input: StartPaymentBillingAddressInput): BarionBillingAddress {
  const [street, street2, street3] = splitStreetLines(input.street)
  const city = fitUtf16(input.city, BARION_BILLING_CITY_MAX)
  const zip = fitUtf16(input.zip, BARION_BILLING_ZIP_MAX)
  return {
    Country: input.country === 'HU' ? 'HU' : 'ZZ',
    ...(city.length > 0 ? { City: city } : {}),
    ...(zip.length > 0 ? { Zip: zip } : {}),
    ...(street !== undefined && street.length > 0 ? { Street: street } : {}),
    ...(street2 !== undefined && street2.length > 0 ? { Street2: street2 } : {}),
    ...(street3 !== undefined && street3.length > 0 ? { Street3: street3 } : {}),
  }
}

function mapPurchaseInformation(input: StartPaymentThreeDsInput): BarionPurchaseInformation {
  const email = input.deliveryEmailAddress.trim()
  return {
    DeliveryTimeframe: 'ElectronicDelivery',
    ...(email.length > 0 ? { DeliveryEmailAddress: email } : {}),
    ShippingAddressIndicator: 'DigitalGoods',
    PurchaseType: 'GoodsAndServicePurchase',
    PurchaseDate: barionUtcTimestamp(input.purchaseDate),
  }
}

function isValidDate(value: Date | null): value is Date {
  return value !== null && !Number.isNaN(value.getTime())
}

function mapPayerAccount(input: StartPaymentThreeDsInput): BarionPayerAccountInformation {
  const account = input.payerAccount
  if (account.kind === 'guest') {
    return { AccountCreationIndicator: 'NoAccount' }
  }
  const accountId = fitUtf16(account.accountId, BARION_ACCOUNT_ID_MAX)
  const created = isValidDate(account.accountCreated) ? account.accountCreated : null
  return {
    ...(accountId.length > 0 ? { AccountId: accountId } : {}),
    ...(created !== null
      ? {
          AccountCreated: barionUtcTimestamp(created),
          AccountCreationIndicator: accountCreationIndicatorFor(created, input.purchaseDate),
        }
      : {}),
  }
}

function mapItem(item: StartPaymentItemInput): BarionItem {
  const name = fitText(item.name, BARION_ITEM_NAME_MAX)
  const description = fitText(item.description, BARION_ITEM_DESCRIPTION_MAX)
  return {
    Name: name,
    Description: description.length > 0 ? description : fitText(name, BARION_ITEM_DESCRIPTION_MAX),
    Quantity: item.quantity,
    Unit: item.unit,
    UnitPrice: item.unitPrice,
    ItemTotal: item.itemTotal,
    ...(item.sku !== undefined ? { SKU: fitText(item.sku, BARION_ITEM_SKU_MAX) } : {}),
  }
}

function mapTransaction(
  transaction: StartPaymentTransactionInput,
  defaultPayee: string,
): BarionPaymentTransaction {
  return {
    POSTransactionId: transaction.posTransactionId,
    Payee: transaction.payee ?? defaultPayee,
    Total: transaction.total,
    Currency: 'HUF',
    ...(transaction.comment !== undefined ? { Comment: transaction.comment } : {}),
    Items: transaction.items.map(mapItem),
  }
}

/** A Start-kérés body-építése külön, tisztán tesztelhető függvényben. */
export function buildPaymentStartRequest(
  params: StartPaymentParams,
  config: BarionClientConfig,
): Omit<BarionPaymentStartRequest, 'POSKey'> {
  if (params.transactions.length === 0) {
    throw new Error('Barion Payment/Start: legalább egy tranzakció kötelező.')
  }

  if (params.recurring !== undefined) {
    if (!config.recurringEnabled) {
      throw new Error(
        'Barion Payment/Start: recurring-előkészítést kért a hívó, de a funkció ki van kapcsolva ' +
          "(BARION_RECURRING_ENABLED !== 'true'). Kapcsold be a flaget, vagy ne add meg a recurring-paramétert.",
      )
    }
    if (params.recurring.initiateRecurrence && !params.recurring.recurrenceId) {
      throw new Error(
        'Barion Payment/Start: initiateRecurrence esetén a recurrenceId megadása kötelező.',
      )
    }
  }

  const cardHolderNameHint = cardHolderNameHintFor(params.cardHolderNameHint)
  const orderNumber =
    params.orderNumber !== undefined ? fitText(params.orderNumber, BARION_ORDER_NUMBER_MAX) : ''
  const threeDs = barionSend3dsEnabled() ? params.threeDs : undefined

  return {
    PaymentType: 'Immediate',
    GuestCheckOut: true,
    FundingSources: ['All'],
    Locale: 'hu-HU',
    Currency: 'HUF',
    PaymentWindow: params.paymentWindow ?? BARION_DEFAULT_PAYMENT_WINDOW,
    PaymentRequestId: params.paymentRequestId,
    ...(orderNumber.length > 0 ? { OrderNumber: orderNumber } : {}),
    ...(params.payerHint !== undefined ? { PayerHint: params.payerHint } : {}),
    ...(cardHolderNameHint !== undefined ? { CardHolderNameHint: cardHolderNameHint } : {}),
    RedirectUrl: params.redirectUrl,
    CallbackUrl: params.callbackUrl,
    Transactions: params.transactions.map((transaction) =>
      mapTransaction(transaction, config.payeeEmail),
    ),
    ...(threeDs !== undefined
      ? {
          BillingAddress: mapBillingAddress(threeDs.billingAddress),
          PurchaseInformation: mapPurchaseInformation(threeDs),
          PayerAccountInformation: mapPayerAccount(threeDs),
          // SOHA nem 'NoChallengeNeeded': a docs szerint ott „the liability is
          // on the merchant" (ChallengePreference). A NoPreference-nél a
          // felelősség a kártyakibocsátóé, a 3DS-ről a Barion dönt.
          ChallengePreference: 'NoPreference',
        }
      : {}),
    ...(params.recurring?.initiateRecurrence
      ? { InitiateRecurrence: true, RecurrenceId: params.recurring.recurrenceId }
      : {}),
  }
}

/**
 * Fizetés indítása (Payment/Start v2). A válasz GatewayUrl-jére kell a vevőt
 * irányítani; a PaymentId-t a rendelésen rögzíti a hívó (orders.barionPaymentId).
 */
export async function startPayment(
  params: StartPaymentParams,
  config?: BarionClientConfig,
): Promise<BarionPaymentStartResponse> {
  const resolvedConfig = config ?? getBarionConfig()
  const request = buildPaymentStartRequest(params, resolvedConfig)
  const response = await barionPost<BarionPaymentStartResponse>(
    '/v2/Payment/Start',
    request,
    resolvedConfig,
  )
  // A PaymentId a Barionban kötőjeles és kötőjel nélküli alakban is előfordul;
  // a rendelésre a kanonikus alak kerül (guid.ts). GUID nélkül a fizetés nem
  // követhető, ezért ez érvénytelen válasz.
  const paymentId = canonicalBarionGuid(response.PaymentId)
  if (paymentId === null) {
    throw new BarionApiError({
      message: 'A Barion Start-válasz nem tartalmaz érvényes PaymentId-t.',
      kind: 'invalid_response',
      endpoint: 'POST /v2/Payment/Start',
    })
  }
  return {
    ...response,
    PaymentId: paymentId,
    ...(Array.isArray(response.Transactions)
      ? {
          Transactions: response.Transactions.map((transaction) => ({
            ...transaction,
            TransactionId: canonicalizeBarionGuid(transaction.TransactionId),
          })),
        }
      : {}),
  }
}
